import React, { useState, useEffect } from 'react';
import { SectionId, POSCartItem } from './types';
import { SAMPLE_POS_PRODUCTS } from './data/posArchitectureData';
import { Header } from './components/Header';
import { Sidebar } from './components/Sidebar';
import { RightTelemetryPanel } from './components/RightTelemetryPanel';
import { SearchModal } from './components/SearchModal';

import { OverviewSection } from './components/sections/OverviewSection';
import { ArchitectureSection } from './components/sections/ArchitectureSection';
import { HardwareHalSection } from './components/sections/HardwareHalSection';
import { TerminalSimulatorSection } from './components/sections/TerminalSimulatorSection';
import { HardwareConsoleSection } from './components/sections/HardwareConsoleSection';
import { DataResilienceSection } from './components/sections/DataResilienceSection';
import { CodeRepositorySection } from './components/sections/CodeRepositorySection';
import { DeploymentBenchmarksSection } from './components/sections/DeploymentBenchmarksSection';

export default function App() {
  const [activeSection, setActiveSection] = useState<SectionId>('overview');
  const [isMobileSidebarOpen, setIsMobileSidebarOpen] = useState(false);
  const [isSearchOpen, setIsSearchOpen] = useState(false);
  const [onlineMode, setOnlineMode] = useState(true);
  const [isFullscreen, setIsFullscreen] = useState(false);
  const [cart, setCart] = useState<POSCartItem[]>([SAMPLE_POS_PRODUCTS[0], SAMPLE_POS_PRODUCTS[1]]);

  // Global keyboard shortcut: Cmd+K / Ctrl+K
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if ((e.metaKey || e.ctrlKey) && e.key === 'k') {
        e.preventDefault();
        setIsSearchOpen(prev => !prev);
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, []);

  const handleToggleFullscreen = () => {
    if (!document.fullscreenElement) {
      document.documentElement.requestFullscreen().catch(() => {});
      setIsFullscreen(true);
    } else {
      if (document.exitFullscreen) {
        document.exitFullscreen().catch(() => {});
      }
      setIsFullscreen(false);
    }
  };

  const handleExportDossier = () => {
    const dossierMarkdown = `# Mobile Solutions POS - Technical Architecture & Systems Matrix
## Framework: .NET Framework 4.8 / Windows Forms / C# 9.0
## Date: ${new Date().toISOString()}

### 1. Executive Summary
High-throughput, mission-critical retail Point of Sale (POS) client built with C# and Windows Forms GDI+ hardware acceleration.
- Barcode Scan-to-Cart latency: <18ms
- Memory Working Set: 84 MB steady state
- Offline Resilience: SQLite with Write-Ahead Logging (WAL)
- Central Synchronization: Microsoft SQL Server 2019 via GZip compressed batches

### 2. Hardware Abstraction Layer (HAL)
- Epson ESC/POS & Star Micronics thermal printers (COM/USB/Ethernet)
- Mettler Toledo & CAS continuous RS-232 weighing scales
- Win32 RawInput window hook (WM_INPUT) for non-focus barcode scanning
- APG & Posiflex 24V RJ-11 cash drawers driven via printer kick pin
- Partner Tech VFD 20x2 customer displays

Generated by Mobile Solutions POS Architecture Matrix Portal.
`;

    const blob = new Blob([dossierMarkdown], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', 'MobileSolutionsPOS_Architecture_Dossier.md');
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const renderActiveSection = () => {
    switch (activeSection) {
      case 'overview':
        return <OverviewSection onSelectSection={setActiveSection} />;
      case 'architecture':
        return <ArchitectureSection />;
      case 'hardware-hal':
        return <HardwareHalSection />;
      case 'terminal-simulator':
        return (
          <TerminalSimulatorSection
            onlineMode={onlineMode}
            onToggleOnlineMode={() => setOnlineMode(prev => !prev)}
            cart={cart}
            setCart={setCart}
          />
        );
      case 'hardware-console':
        return <HardwareConsoleSection />;
      case 'data-resilience':
        return <DataResilienceSection />;
      case 'code-repository':
        return <CodeRepositorySection />;
      case 'benchmarks':
        return <DeploymentBenchmarksSection />;
      case 'deployment':
        return <DeploymentBenchmarksSection />;
      default:
        return <OverviewSection onSelectSection={setActiveSection} />;
    }
  };

  return (
    <div className="min-h-screen bg-[#060A17] text-[#F8FAFC] flex flex-col font-sans bg-cyber-grid selection:bg-[#00B4D8]/30 selection:text-[#48CAE4]">
      {/* Top Cyber Navigation Bar */}
      <Header
        activeSection={activeSection}
        onSelectSection={setActiveSection}
        onToggleMobileSidebar={() => setIsMobileSidebarOpen(prev => !prev)}
        isMobileSidebarOpen={isMobileSidebarOpen}
        onOpenSearch={() => setIsSearchOpen(true)}
        onExportDossier={handleExportDossier}
        isFullscreen={isFullscreen}
        onToggleFullscreen={handleToggleFullscreen}
      />

      {/* Main Structural Body */}
      <div className="flex-1 flex pt-16">
        {/* Left Fixed 280px Navigation Tree */}
        <Sidebar
          activeSection={activeSection}
          onSelectSection={setActiveSection}
          isOpenMobile={isMobileSidebarOpen}
          onCloseMobile={() => setIsMobileSidebarOpen(false)}
          onOpenSearch={() => setIsSearchOpen(true)}
        />

        {/* Central Content Canvas (with 280px left margin on desktop and 256px right margin on xl) */}
        <main className="flex-1 min-w-0 px-4 sm:px-8 py-8 lg:ml-72 xl:mr-64 transition-all">
          <div className="max-w-5xl mx-auto">
            {renderActiveSection()}
          </div>
        </main>

        {/* Right 240px Telemetry & Nodal Navigation Panel */}
        <RightTelemetryPanel
          activeSection={activeSection}
          onSelectSection={setActiveSection}
          onlineMode={onlineMode}
          onToggleOnlineMode={() => setOnlineMode(prev => !prev)}
          cartCount={cart.length}
        />
      </div>

      {/* Global Quick Search Modal (Cmd+K) */}
      <SearchModal
        isOpen={isSearchOpen}
        onClose={() => setIsSearchOpen(false)}
        onSelectSection={setActiveSection}
      />
    </div>
  );
}
